#!/usr/bin/env python3
"""Emit GemJoin/Runtime.lean: the subject runtime as a ByteArray literal.

Usage: python3 -I tools/gen_runtime.py <runtime.hex> > GemJoin/Runtime.lean
The keccak256 of the bytes is checked separately (cast keccak) against D8.
"""
import sys

h = open(sys.argv[1]).read().strip()
assert h.startswith("0x")
b = bytes.fromhex(h[2:])
rows = [", ".join("0x%02x" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
print("-- Generated by tools/gen_runtime.py from tests/reference/getters/subject/runtime.hex.")
print("-- GemJoin ETH-A runtime, %d bytes, keccak256 0x8661c673677de206fda20eb1883063ea4a827c2ac1c7f232dd30e276d20874fa (D8)." % len(b))
print("namespace GemJoin\n")
print("def runtimeBytes : Array UInt8 := #[")
print(",\n".join("  " + r for r in rows))
print("]\n")
print("def runtime : ByteArray := ⟨runtimeBytes⟩\n")
print("end GemJoin")
